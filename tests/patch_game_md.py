"""Дополняет knowledge/GAME.md находками второй сессии (башня, рюкзак, таланты, облако)."""
from __future__ import annotations

from pathlib import Path

path = Path(__file__).resolve().parents[1] / "knowledge" / "GAME.md"
text = path.read_text(encoding="utf-8")

marker = "## Экономика и прогрессия"
assert marker in text, "не найден раздел"

addition = '''## Новый герой без клана: как качаться (замеры 11.11.2026)

Аккаунт `fire white ii` (создан 10.11.2026, воин, север) показал, что путь прокачки
до 10 уровня устроен иначе, чем у кланового героя:

| Что | Детали |
|---|---|
| Бесплатный бой | `/game/ogreDungeon` («Забытый склеп») — даётся **ежедневной наградой** на главной (ссылка `awardLink`), а не сам по себе. Пока герой не забрал награду, бесплатных подземелий 0 |
| Главный фарм | **Башня** `/game/towers` → локация «Курган». Бой бесплатный и бесконечный: кнопка «Бить врагов» (`damageRandomEnemyLink`), каждый убитый враг капает опыт, бутылочки, железо и вещи. Опыт: ~35–50 за убийство |
| Подземелья | `/game/dungeons` открываются с 10 уровня («требуется 10 уровень»), раньше недоступны |
| Поход | `/journey` — с 10 уровня |
| Ограничение | Уровень 10+ → в кланы пускают (правило «только игроки выше 10 уровня») |

### Рюкзак — главный тормоз прокачки

- Рюкзак: 20 слотов, сундук (`/user/store`): ещё 20.
- Когда рюкзак забит, новый дроп не помещается и **опыт героя перестаёт расти** — симптом
  выглядит как «агент фармит, а опыт стоит».
- Решение: надеть вещи с пометкой «Лучше (+N)» (`items:N:wearLink`) и остальные
  переложить в сундук (`items:N:toStoreLink`). Когда забиты оба — включаем более
  агрессивный авторазбор (`autoCrackUncommonLink`), чтобы дропы сразу шли в железо/мифрил.
- Тир вещей виден по иконке: `bonuscopper` обычные, `bonusgreen` необычные, `bonusrare`
  редкие, `bonusepic` эпические. Режим «обычные вещи» не ломает редкие/эпические —
  из-за этого рюкзак и забивался.

### Таланты (страница не открывается)

- `/user/stances` показывает список веток и ссылку на талант `../user/talent/0/<id>`.
- Переход по этой ссылке (и в браузере, и по прямому GET) **уводит на главную** —
  страница конкретного таланта не рендерится, кнопки «выучить» нет.
- Поэтому очко таланта (1 за уровень с 10-го) пока тратить нечем. Агент не должен
  на этом застревать: делает одну попытку и возвращается к талантам через 30 минут.

### Прочее

- На странице героя есть кнопка **«Хочу в клан»** — это и есть отметка для поиска
  игроков в клан (у героя без клана она появляется автоматически).
- Покупка опыта у мудреца (`/trade/ironmaster`) низкоуровневому герою недоступна:
  страница отдаёт главную. Становется доступна позже (уровень 10+).
- Магазин легиона открывается с 15 уровня.

'''

text = text.replace(marker, addition + marker, 1)
